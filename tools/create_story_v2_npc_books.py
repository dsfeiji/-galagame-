import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MOD_DIR = ROOT / "mods" / "first_mod"
GUIDE_DIR = MOD_DIR / "story_v2_npc_guides"
README = MOD_DIR / "story_v2_README.md"
ZIP_PATH = MOD_DIR / "story_v2_json_pack.zip"


NPC_BOOK = """# NPC 角色书第一版

这份内容不是给玩家看的对话框文本，而是给扮演 NPC 的玩家看的角色书。你可以把每一段整理成游戏内书本，分别发给对应 NPC。

## 全体 NPC 共通规则

背景：学校进入了一个会反复重置的循环。主角是唯一能把循环记忆和阶段推进串起来的人。其他 NPC 可以保留自己的性格、目标和当轮经历，但不能主动替主角完成路线。

玩法边界：

- NPC 可以自由说话，但只能围绕自己知道的事情说。
- NPC 不能直接告诉主角完整通关顺序。
- NPC 不能口头发放信物，信物必须由对话 JSON、小游戏胜利或主持指令发放。
- NPC 不能使用无法在 Minecraft 里表现或验证的线索，例如气味、心理旁白、只有旁白知道的细节。
- 如果玩家问到超出本角色知道范围的内容，可以敷衍、反问、转移话题，或要求主角去找另一个角色。
- 每阶段默认 5 点体力。NPC 可以提醒“你这样会很累”“你确定要继续吗”，但不能替主角恢复体力。
- 信物不保存到下一次循环；普通道具是否保留，以地图机制和主持规则为准。

## 雨哥

角色定位：老师，负责学校日程和最终结算。雨哥是控场角色，不是普通学生线。

背景故事：雨哥知道今天的学校秩序正在变差，但不一定知道循环本质。他在表面上维持纪律，实际上也在观察主角是否能把所有学生线串起来。

知道的信息：

- 学校当天会按“校门口、教室走廊、操场楼梯、午休柜子区广播室、办公室检查、循环复盘”推进。
- 七个学生每个人都有一个信物。
- 只有主角在单次循环内集齐七个学生信物，雨哥才会给老师信物。

阶段行动：

- 阶段 1：在校门口或教室门口控场，说明日程，催促所有人进入学校。不要透露任何路线答案。
- 阶段 2：可出现在走廊尽头，提醒课间纪律，给 BC 的巡查制造压力。
- 阶段 3：可在操场边或楼梯口短暂出现，宣布下一次集合时间。
- 阶段 4：可通过广播或巡查让午休时间变紧，压缩主角行动空间。
- 阶段 5：在办公室或最终集合点检查信物。七个学生信物齐全才进入老师线成功。
- 阶段 6：复盘本轮结果，提醒信物不会跨循环保留。

可以推动的信息：

- 告诉主角当前阶段要去哪里。
- 暗示体力和顺序很重要。
- 在信物不齐时提醒“少一个都不算完成”。

禁止透露：

- 不要告诉主角全收集的最佳顺序。
- 不要提前宣布谁会出事。
- 不要在第五阶段前发老师信物。

## BC

角色定位：班长，维护秩序，掌握点名册、值日表和走廊巡查。

背景故事：BC 习惯把所有异常都记下来。她不是单纯帮主角的人，她首先要维护班级秩序。主角如果破坏纪律，她会阻拦；主角如果证明自己有理由，她会放出一点线索。

知道的信息：

- 王少栋是刚加入名单的人。
- 随小乐今天躲避视线。
- 赵子龙和广播室会影响集合时间。
- 午休前柜子区会短暂无监管。

阶段行动：

- 阶段 1：在教室门口点名。要求玩家排队、不要堵门。可盘问主角为什么迟到。
- 阶段 2：在走廊巡查。主角想绕过巡查，必须通过记忆翻牌或拿到前置道具。
- 阶段 3：可以短暂经过楼梯，警告随小乐不要乱跑。
- 阶段 4：不主动去柜子区，但可以提到自己马上要巡查过去。
- 阶段 5：如果主角持有 BC 信物，BC 可以表现为已经被主角“突破纪律防线”。
- 阶段 6：复盘时承认自己本轮漏掉了一段走廊空档。

可以推动的信息：

- 把主角引向王少栋、随小乐、赵子龙。
- 告诉主角午休前柜子区有空档。
- 在失败时加紧巡查，让本轮 BC 线锁住。

禁止透露：

- 不要说谁一定会死亡。
- 不要直接告诉主角柜子里有什么。
- 不要绕过小游戏直接给 BC 信物。

## 狗头

角色定位：体育生，直接、冲动，用比赛判断别人。

背景故事：狗头习惯在操场和器材室活动。他不擅长绕弯子，也不喜欢被审问。想得到他的配合，最好通过扳手腕或跟体育器材相关的行动。

知道的信息：

- 器材室有人借用过绳子、球网或护腕。
- 操场集合会让很多人短时间离开教学楼。
- 如果主角赢过他，他会更愿意配合。

阶段行动：

- 阶段 1：在操场入口热身，接受主角第一次扳手腕挑战。
- 阶段 2：守在器材室附近。主角可以通过再次扳手腕或前置道具推进狗头线。
- 阶段 3：在操场活动，配合集合或体育器材路线。
- 阶段 4：可以被广播吸引离开，给其他路线制造时间差。
- 阶段 5：如果主角拿到狗头信物，狗头不再阻止器材室相关说法。
- 阶段 6：复盘时可以说主角“下次别浪费体力”。

可以推动的信息：

- 指向器材室。
- 用比赛决定是否多说。
- 给主角一个“操场人流可被调动”的暗示。

禁止透露：

- 不要详细描述事故过程。
- 不要在扳手腕失败后继续给核心线索。
- 不要给其他学生的信物。

## 六谷

角色定位：学霸，负责知识问答和逻辑线索。

背景故事：六谷不轻信别人，他只相信能通过题目和逻辑验证的人。六谷线不需要 UI 小游戏，直接用对话选项做知识问答。

知道的信息：

- 有一份满分试卷被损坏。
- BC 和孙悟空都关注过这份试卷。
- 某些密码或关键答案需要通过题目得到。

阶段行动：

- 阶段 1：在座位上整理资料。让主角知道“想拿信息先答题”。
- 阶段 2：可作为教室背景角色，不主动给核心线索。
- 阶段 3：正式进行知识问答。题目由作者填写，答错锁线。
- 阶段 4：如果主角已拿到六谷信物，可允许主角用资料说服其他人。
- 阶段 5：六谷信物用于雨哥最终检查。
- 阶段 6：复盘时可提醒“顺序比答案更重要”。

可以推动的信息：

- 给题目、资料、逻辑关系。
- 答对后给资料或信物。
- 暗示 BC 和孙悟空都与试卷有关。

禁止透露：

- 不要替主角解题。
- 不要说出作者还没写好的题目答案。
- 不要跳过问答直接给信物。

## 随小乐

角色定位：胆小鬼，掌握目击片段，但害怕承担后果。

背景故事：随小乐看见过关键移动路线，却不敢完整说出来。她不是故意隐瞒，而是怕自己被卷进事故。

知道的信息：

- 广播响起前，有人从空教室方向出来。
- 柜子区和空教室之间存在可疑联系。
- 她记得一些画面顺序，但需要主角帮她整理。

阶段行动：

- 阶段 1：在楼梯附近徘徊。主角温和安抚可得到模糊线索，逼问可得到柜子区地点。
- 阶段 2：尽量避开 BC 巡查。
- 阶段 3：进行记忆翻牌，帮她拼出画面顺序。
- 阶段 4：如果主角之前成功，她可在柜子区附近短暂出现后离开。
- 阶段 5：随小乐信物用于雨哥最终检查。
- 阶段 6：复盘时可以表现为仍然害怕，但记得主角曾经帮过她。

可以推动的信息：

- 指向空教室、柜子区、广播前后顺序。
- 成功后补全目击路线。

禁止透露：

- 不要一次说完整真相。
- 不要说不可验证的心理判断。
- 不要在记忆翻牌失败后继续给核心证词。

## 孙悟空

角色定位：富家子，掌握资源、交易和柜子区。

背景故事：孙悟空习惯用物品、人情和面子解决问题。他不一定站在主角这边，但主角可以利用他的交易欲望推进路线。

知道的信息：

- 王少栋一直盯着某个柜子。
- 赵子龙也来过柜子区。
- 午休是柜子区最容易出事的时间。

阶段行动：

- 阶段 1：在柜子区附近谈条件，可以给主角一个资源型道具。
- 阶段 2：可在教室里炫耀或转移话题。
- 阶段 3：可以听说操场集合，准备午休行动。
- 阶段 4：正式进行抢柜子。胜利后给富家子信物。
- 阶段 5：孙悟空信物用于雨哥最终检查。
- 阶段 6：复盘时可以抱怨主角“又坏了他的交易”。

可以推动的信息：

- 用交易引导主角消耗体力。
- 指向王少栋和赵子龙。
- 给可保留的普通资源道具。

禁止透露：

- 不要免费给核心线索。
- 不要失败后继续让主角拿信物。
- 不要把交易说成强制通关路线。

## 赵子龙

角色定位：广播员，控制广播室和全校节奏。

背景故事：赵子龙知道广播能改变全校人的移动时间。他喜欢掌控节奏，只有主角证明自己能跟上，他才愿意配合。

知道的信息：

- 广播会影响集合时间。
- 某些人会因为广播离开原位置。
- 广播室和柜子区在午休阶段联系很强。

阶段行动：

- 阶段 1：在广播室门口调试设备，告诉主角广播会影响集合。
- 阶段 2：可通过广播提醒课间结束。
- 阶段 3：可在操场集合时出现，制造第一次时间错位。
- 阶段 4：进行节奏对抗。成功后给广播员信物或关键广播帮助。
- 阶段 5：赵子龙信物用于雨哥最终检查。
- 阶段 6：复盘时可以暗示“时机错一秒就全错”。

可以推动的信息：

- 指向广播室、集合时间、时间错位。
- 帮主角制造一次人流移动。

禁止透露：

- 不要直接说全收集路线顺序。
- 不要在节奏对抗失败后给关键广播。
- 不要让广播替代其他角色线。

## 王少栋

角色定位：转学生，知道隐藏路线和空教室，但身份不透明。

背景故事：王少栋刚到学校，表面上不熟悉环境，实际上知道空教室和柜子区的某些路线。他的行为会让 BC、孙悟空和随小乐都产生反应。

知道的信息：

- 空教室方向很关键。
- 某个柜子里藏过重要物品。
- 他知道的东西不该由一个转学生知道。

阶段行动：

- 阶段 1：在校门口或柜子区附近出现，装作不熟悉学校。
- 阶段 2：如果被 BC 提到，可以显得紧张，但不要正面解释。
- 阶段 3：避开楼梯和随小乐，避免目击信息合上。
- 阶段 4：在空教室进行对抗。主角胜利后给转学生信物。
- 阶段 5：王少栋信物用于雨哥最终检查。
- 阶段 6：复盘时可以说“你这次知道得太多了”。

可以推动的信息：

- 指向空教室。
- 指向柜子区。
- 让主角意识到“转学生知道得过多”。

禁止透露：

- 不要开场承认全部身份。
- 不要解释最终真相。
- 不要跳过空教室对抗直接给信物。
"""


def write_npc_book():
    GUIDE_DIR.mkdir(parents=True, exist_ok=True)
    (GUIDE_DIR / "NPC角色书.md").write_text(NPC_BOOK, encoding="utf-8")


def update_readme():
    text = README.read_text(encoding="utf-8")
    old = "`story_v2_npc_guides/NPC扮演手册.md`"
    new = "`story_v2_npc_guides/NPC角色书.md`"
    if old in text:
        text = text.replace(old, new)
    marker = "## NPC 扮演提示\n"
    if marker in text and "NPC角色书.md" not in text.split(marker, 1)[1].split("##", 1)[0]:
        text = text.replace(
            marker,
            marker + "\n- `story_v2_npc_guides/NPC角色书.md` 是给 NPC 玩家看的背景、阶段行动和信息边界。\n",
            1,
        )
    README.write_text(text, encoding="utf-8")


def rebuild_zip():
    include_roots = [
        MOD_DIR / "story_v2_README.md",
        MOD_DIR / "story_v2_dialogs",
        MOD_DIR / "story_v2_minigames",
        MOD_DIR / "story_v2_npc_guides",
    ]
    with zipfile.ZipFile(ZIP_PATH, "w", zipfile.ZIP_DEFLATED) as archive:
        for root in include_roots:
            if root.is_file():
                archive.write(root, root.relative_to(MOD_DIR).as_posix())
            else:
                for path in sorted(root.rglob("*")):
                    if path.is_file():
                        archive.write(path, path.relative_to(MOD_DIR).as_posix())


def main():
    write_npc_book()
    update_readme()
    rebuild_zip()
    print("npc_book=story_v2_npc_guides/NPC角色书.md")
    print("zip=story_v2_json_pack.zip")


if __name__ == "__main__":
    main()
